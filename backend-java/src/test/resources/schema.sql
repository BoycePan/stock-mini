-- 新闻/公告统一存储。Go 侧 DDL 使用 TIMESTAMPTZ；H2 测试库不支持该别名（已验证 2.2.224/2.3.232），
-- 故用全称 TIMESTAMP WITH TIME ZONE，二者在 PostgreSQL 中语义完全一致。
CREATE TABLE IF NOT EXISTS news_feed (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_code   VARCHAR(10),
    title        VARCHAR(512),
    summary      TEXT,
    url          VARCHAR(1024),
    source       VARCHAR(64),
    published_at TIMESTAMP WITH TIME ZONE
);
-- 去重索引：与 Go 侧 BatchSave 的 ON CONFLICT DO NOTHING 语义一致（同 stock_code+title+published_at 跳过）
CREATE UNIQUE INDEX IF NOT EXISTS uk_news_feed_dedup ON news_feed (stock_code, title, published_at);

-- 指数/行情实时快照（定时任务每 60s 覆盖刷新，仅存最新值）
CREATE TABLE IF NOT EXISTS quote_snapshot (
    code       VARCHAR(20) PRIMARY KEY,
    name       VARCHAR(64),
    price      NUMERIC(18,4),
    pct_change NUMERIC(10,2),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- RSS 新闻源配置表：源列表走数据库（RssNewsScheduler 每分钟读取 enabled=true 的源拉取新闻）。
-- 生产 PostgreSQL 执行同份 DDL 见 scripts/rss_source.sql（含 COMMENT ON 中文注释）。
CREATE TABLE IF NOT EXISTS rss_source (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- 主键（自增）
    name            VARCHAR(64)  NOT NULL,                                 -- 源名称（展示用，如“少数派”）
    url             VARCHAR(512) NOT NULL,                                 -- RSS/Atom feed 地址
    via_worker      BOOLEAN      NOT NULL DEFAULT FALSE,                   -- 是否走 Cloudflare Worker 转发（海外源=true）
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,                    -- 是否启用（false 则跳过，保留不删）
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,                   -- 软删除标记（true=已删，列表默认不展示）
    last_status     VARCHAR(16),                                           -- 最近一次拉取状态：ok / fail（null=未拉过）
    last_error      VARCHAR(512),                                          -- 最近一次拉取失败原因
    last_fetch_at   TIMESTAMP,                                             -- 最近一次拉取时间
    last_item_count INT                                                     -- 最近一次拉取解析条目数
);
-- URL 唯一索引：防止重复源（代码种子与手工插入都幂等）
CREATE UNIQUE INDEX IF NOT EXISTS uk_rss_source_url ON rss_source (url);

-- 用户点击/行为打点表（生产 PostgreSQL 同份 DDL 见 scripts/click_event.sql，含 COMMENT 中文注释）
CREATE TABLE IF NOT EXISTS click_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR(64)  NOT NULL,
    user_id      BIGINT,
    session_id   VARCHAR(64),
    event_type   VARCHAR(32),
    event_name   VARCHAR(128) NOT NULL,
    page         VARCHAR(128),
    target       VARCHAR(128),
    props        TEXT,
    duration_ms  INTEGER,
    client_ts    BIGINT,
    server_ts    TIMESTAMP WITH TIME ZONE DEFAULT now(),
    ip           VARCHAR(64),
    platform     VARCHAR(32),
    app_version  VARCHAR(32)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_click_event_event_id ON click_event (event_id);
CREATE INDEX IF NOT EXISTS idx_click_event_name_ts ON click_event (event_name, server_ts);
CREATE INDEX IF NOT EXISTS idx_click_event_user_ts ON click_event (user_id, server_ts);
CREATE INDEX IF NOT EXISTS idx_click_event_type_ts ON click_event (event_type, server_ts);

-- 前端展示配置表：结构轴(node_type+parent_id) × 交付轴(cfg_type)，按 target 分端。
-- 生产 PostgreSQL 同份 DDL 见 scripts/app_config.sql（含 COMMENT ON 中文注释）；
-- cfg_value 存 JSON 文本（TEXT 列，对齐 click_event.props；H2 无 JSONB 别名，与生产 TEXT 口径一致）。
-- 顶层 cfg_key 唯一性由 Service 层校验（H2 不支持生产侧 partial unique index，语义等价）。
CREATE TABLE IF NOT EXISTS app_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT,
    node_type   VARCHAR(16) NOT NULL DEFAULT 'item',
    cfg_type    VARCHAR(32) NOT NULL DEFAULT 'display',
    cfg_key     VARCHAR(64) NOT NULL,
    cfg_value   TEXT,
    remark      VARCHAR(255),
    target      VARCHAR(32) NOT NULL DEFAULT 'all',
    sort        INT         NOT NULL DEFAULT 0,
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_app_config_delivery ON app_config (cfg_type, target, enabled);

-- 前端公告内容表：分端 + 展示位置 + 有效期 + 置顶/排序。
-- 生产 PostgreSQL 同份 DDL 见 scripts/notice.sql（含 COMMENT ON 中文注释）。
CREATE TABLE IF NOT EXISTS notice (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(32) NOT NULL DEFAULT 'notice',
    title       VARCHAR(128),
    target      VARCHAR(32) NOT NULL DEFAULT 'all',
    position    VARCHAR(32) NOT NULL DEFAULT 'settings',
    sort        INT         NOT NULL DEFAULT 0,
    pinned      BOOLEAN     NOT NULL DEFAULT FALSE,
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    valid_from  TIMESTAMP,
    valid_to    TIMESTAMP,
    config      TEXT,
    created_at  TIMESTAMP   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notice_display ON notice (target, position, enabled);
